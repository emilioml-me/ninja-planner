import { safeIntegrationFetch, getServiceConfig, postToService } from './client.js';
import type { IntegrationResult, CrmSummary, CrmDealsResult, CrmClientsResult } from './types.js';

/**
 * crm-ninja has no multi-tenant concept of its own — its API scopes every query by a single
 * crm-ninja user id ("tenant"), sent as the X-Tenant-ID header. Each ninja-planner workspace
 * that wants CRM data must be linked to one such id (workspaces.crm_ninja_tenant_id) — see
 * routes/integrations.ts's crm-tenant endpoints for how that mapping is set.
 */
function tenantHeaders(tenantId: number): Record<string, string> {
  return { 'X-Tenant-ID': String(tenantId) };
}

/**
 * Fetch client/MRR summary from crm-ninja (client-ninja) for the given tenant.
 *
 * crm-ninja must expose:
 *   GET /api/internal/summary
 *   Authorization: Bearer <CRM_NINJA_API_KEY>
 *   X-Tenant-ID: <crm-ninja user id>
 *
 * Expected response shape: CrmSummary
 */
export async function fetchCrmSummary(tenantId: number): Promise<IntegrationResult<CrmSummary>> {
  return safeIntegrationFetch<CrmSummary>('CRM_NINJA', '/api/internal/summary', 5_000, tenantHeaders(tenantId));
}

/**
 * Fetch closed/won deals from crm-ninja for revenue sync, for the given tenant.
 *
 * crm-ninja must expose:
 *   GET /api/internal/deals?stage=closed_won
 *   Authorization: Bearer <CRM_NINJA_API_KEY>
 *   X-Tenant-ID: <crm-ninja user id>
 *
 * Expected response shape: CrmDealsResult
 */
export async function fetchCrmDeals(tenantId: number, stage = 'closed_won'): Promise<IntegrationResult<CrmDealsResult>> {
  return safeIntegrationFetch<CrmDealsResult>(
    'CRM_NINJA',
    `/api/internal/deals?stage=${encodeURIComponent(stage)}`,
    5_000,
    tenantHeaders(tenantId),
  );
}

/**
 * Fetch the full contact/client roster from crm-ninja for the given tenant, for a bulk sync
 * into ninja-planner's local `clients` table (POST /api/integrations/sync-clients).
 *
 * crm-ninja must expose:
 *   GET /api/internal/clients
 *   Authorization: Bearer <CRM_NINJA_API_KEY>
 *   X-Tenant-ID: <crm-ninja user id>
 *
 * Expected response shape: CrmClientsResult
 */
export async function fetchCrmClients(tenantId: number): Promise<IntegrationResult<CrmClientsResult>> {
  return safeIntegrationFetch<CrmClientsResult>('CRM_NINJA', '/api/internal/clients', 5_000, tenantHeaders(tenantId));
}

/**
 * Verifies a one-time linking code (generated by the crm-ninja user themselves, via
 * POST /api/integrations/ninja-planner/link-code there) before a workspace is allowed to link
 * to that crm-ninja tenant id. Without this, PATCH /api/integrations/crm-tenant would accept any
 * guessed integer tenant id with no proof the linking workspace actually controls that account —
 * a cross-tenant IDOR letting one workspace pull an unrelated company's CRM data.
 *
 * crm-ninja must expose:
 *   POST /api/internal/verify-tenant-link  { tenantId, code }
 *   Authorization: Bearer <CRM_NINJA_API_KEY>
 *
 * Returns false (never throws) if the integration isn't configured or the call fails — callers
 * must treat that as "not verified", not "skip verification".
 */
export async function verifyCrmTenantLink(tenantId: number, code: string): Promise<boolean> {
  const config = getServiceConfig('CRM_NINJA');
  if (!config) return false;
  try {
    const result = await postToService<{ valid: boolean }>(
      config,
      '/api/internal/verify-tenant-link',
      { tenantId, code },
    );
    return result.valid === true;
  } catch {
    return false;
  }
}
